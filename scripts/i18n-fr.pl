#!/usr/bin/perl
# Adds translations keyed by the French text, then rebuilds the shared dictionaries.
# usage: perl scripts/i18n-fr.pl <French list, one per line> <N<TAB>en<TAB>es<TAB>de<TAB>it<TAB>pt files…>
# Line N of the French list gets the translations of line "N<TAB>…". Missing lines are skipped.
# Afterwards crates/studio-ui/i18n/all-<code>.tsv holds every app's entries, so a text translated
# in one app is translated in all of them.
use strict; use warnings; use utf8;
my @codes = qw(en es de it pt);
my ($list, @files) = @ARGV;
my %tr;
if ($list) {
  open my $in, '<:utf8', $list or die "$list: $!";
  my @fr = map { s/\r?\n$//r } <$in>;
  close $in;
  for my $f (@files) {
    open my $t, '<:utf8', $f or die "$f: $!";
    while (<$t>) {
      s/\r?\n$//;
      my ($n, @cols) = split /\t/, $_, -1;
      next unless defined $n && $n =~ /^\d+$/ && $fr[$n - 1];
      die "$f: line $n has " . scalar(@cols) . " columns\n" if @cols != @codes;
      $tr{$fr[$n - 1]} = \@cols;
    }
  }
}
my @dirs = (glob('apps/*/i18n'), 'crates/studio-ui/i18n');
my %all;
for my $dir (@dirs) {
  my %have;
  for my $k (0 .. $#codes) {
    my $file = "$dir/$codes[$k].tsv";
    my @lines;
    if (open my $d, '<:utf8', $file) { @lines = map { s/\r?\n$//r } <$d>; close $d }
    my %seen;
    for (@lines) {
      my ($fr, $x) = split /\t/, $_, 2;
      next if !defined $x || $fr =~ /^#/;
      if ($k == 0 && $x eq '' && $tr{$fr}) { $x = $tr{$fr}[0]; $_ = "$fr\t$x" }
      $seen{$fr} = 1;
      $have{$fr} = 1 if $k == 0;
      $all{$codes[$k]}{$fr} //= $x if $x ne '';
    }
    if ($k > 0) {
      for my $fr (sort keys %have) {
        next if $seen{$fr} || !$tr{$fr};
        push @lines, "$fr\t$tr{$fr}[$k]";
        $all{$codes[$k]}{$fr} //= $tr{$fr}[$k];
      }
    }
    @lines = ("# French text<TAB>translation. One line per text; a missing line falls back to English.") unless @lines;
    open my $o, '>:utf8', $file or die; print $o map { "$_\n" } @lines; close $o;
  }
}
for my $c (@codes) {
  open my $o, '>:utf8', "crates/studio-ui/i18n/all-$c.tsv" or die;
  print $o "# Generated by scripts/i18n-fr.pl from every app's dictionary. Do not edit.\n";
  print $o "$_\t$all{$c}{$_}\n" for sort keys %{ $all{$c} };
  close $o;
  printf "all-%s.tsv %5d entries\n", $c, scalar keys %{ $all{$c} };
}
